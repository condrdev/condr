#!/usr/bin/env python3
"""Turns assets/agents/*.svg into the Android app's vector drawables (ADR 0048).

Each mark is a few <path> elements on a 24-unit viewBox, filled with currentColor; the
drawable keeps the geometry, takes evenodd where the SVG asks, and tints with the
theme's colorControlNormal like every other icon. Only the kinds Condr supports get one,
those with a spec in crates/condr-core/src/agent/, as the iOS app's asset catalog has. Run
after changing assets/agents/.
"""
from __future__ import annotations

import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCE = ROOT / "assets" / "agents"
SPECS = ROOT / "crates" / "condr-core" / "src" / "agent"
TARGET = ROOT / "mobile" / "android" / "app" / "src" / "main" / "res" / "drawable"
NS = "{http://www.w3.org/2000/svg}"


def path_data(element: ET.Element) -> str | None:
    """A <path>'s data, or the basic shapes (rect, circle, ellipse, polygon, polyline) as one."""
    tag = element.tag.removeprefix(NS)
    get = lambda name, default="0": float(element.get(name, default))
    if tag == "path":
        return element.get("d")
    if tag == "rect":
        x, y, w, h = get("x"), get("y"), get("width"), get("height")
        rx = get("rx", element.get("ry", "0"))
        ry = get("ry", str(rx))
        if rx == 0 and ry == 0:
            return f"M{x:g},{y:g} h{w:g} v{h:g} h{-w:g} z"
        return (
            f"M{x + rx:g},{y:g} h{w - 2 * rx:g} a{rx:g},{ry:g} 0 0 1 {rx:g},{ry:g} v{h - 2 * ry:g}"
            f" a{rx:g},{ry:g} 0 0 1 {-rx:g},{ry:g} h{-(w - 2 * rx):g} a{rx:g},{ry:g} 0 0 1 {-rx:g},{-ry:g}"
            f" v{-(h - 2 * ry):g} a{rx:g},{ry:g} 0 0 1 {rx:g},{-ry:g} z"
        )
    if tag in ("circle", "ellipse"):
        cx, cy = get("cx"), get("cy")
        rx = get("r") if tag == "circle" else get("rx")
        ry = rx if tag == "circle" else get("ry")
        return f"M{cx - rx:g},{cy:g} a{rx:g},{ry:g} 0 1 0 {2 * rx:g},0 a{rx:g},{ry:g} 0 1 0 {-2 * rx:g},0 z"
    if tag in ("polygon", "polyline"):
        points = element.get("points", "").replace(",", " ").split()
        pairs = [f"{points[i]},{points[i + 1]}" for i in range(0, len(points) - 1, 2)]
        if not pairs:
            return None
        return "M" + " L".join(pairs) + (" z" if tag == "polygon" else "")
    return None


def convert(svg: pathlib.Path) -> str:
    root = ET.parse(svg).getroot()
    box = [float(n) for n in root.get("viewBox", "0 0 24 24").split()]
    default_rule = root.get("fill-rule", "nonzero")
    paths = []
    for element in root.iter():
        data = path_data(element)
        if not data:
            continue
        rule = element.get("fill-rule", default_rule)
        fill_type = ' android:fillType="evenOdd"' if rule == "evenodd" else ""
        paths.append(f'    <path android:fillColor="#FFFFFFFF"{fill_type} android:pathData="{data}" />')
    if not paths:
        sys.exit(f"{svg.name}: no <path> to convert")
    body = "\n".join(paths)
    return f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by script/generate-android-agent-marks.py from assets/agents/{svg.name}; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="{box[2]:g}"
    android:viewportHeight="{box[3]:g}"
    android:tint="?attr/colorControlNormal">
{body}
</vector>
"""


def main() -> None:
    TARGET.mkdir(parents=True, exist_ok=True)
    for svg in sorted(SOURCE.glob("*.svg")):
        if not (SPECS / f"{svg.stem}.rs").exists():
            continue
        name = "agent_" + re.sub(r"[^a-z0-9]", "_", svg.stem.lower())
        (TARGET / f"{name}.xml").write_text(convert(svg))
        print(name)


if __name__ == "__main__":
    main()
